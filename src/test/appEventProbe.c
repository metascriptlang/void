long long appEventProbeValue(const char *name) {
	for (size_t i = 0; i < sizeof TABLE / sizeof TABLE[0]; i++) {
		if (strcmp(TABLE[i].name, name) == 0) return TABLE[i].value;
	}
	return LLONG_MIN;
}

int appEventProbeEventSize(void) { return (int)sizeof(VoidAppEvent); }

const void *appEventProbeFilled(void) {
	static VoidAppEvent e;
	memset(&e, 0, sizeof e);
	e.frameCount = 0x1122334455667788ULL;
	e.type = VOID_EVENT_TEXT_INPUT;
	e.keyCode = VOID_KEY_MENU;
	e.charCode = 0xAABBCCDDu;
	e.keyRepeat = true;
	e.modifiers = VOID_MODIFIER_SHIFT | VOID_MODIFIER_MMB;
	e.mouseButton = VOID_MOUSE_MIDDLE;
	e.mouseX = 1.5f;
	e.mouseY = 2.5f;
	e.mouseDx = 3.5f;
	e.mouseDy = 4.5f;
	e.scrollX = 5.5f;
	e.scrollY = 6.5f;
	e.windowWidth = 7;
	e.windowHeight = 8;
	e.framebufferWidth = 9;
	e.framebufferHeight = 10;
	e.touchCount = VOID_MAX_TOUCHPOINTS;
	for (int i = 0; i < VOID_MAX_TOUCHPOINTS; i++) {
		e.touches[i].identifier = (uintptr_t)(100 + i);
		e.touches[i].x = 0.25f * (float)(i + 1);
		e.touches[i].y = 0.5f * (float)(i + 1);
		e.touches[i].changed = (i % 2) == 1;
	}
	return &e;
}
