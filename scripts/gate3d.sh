#!/bin/sh
# The void3d gate: everything a void3d commit has to survive, in one command.
#
#     sh scripts/gate3d.sh
#
# Stages, each printing one PASS / FAIL / SKIP line:
#
#   prepare   regenerate out/tmp/campfireScene.ms and the fourteen capture entries
#   tests     msc test out/tmp/test2d.ms
#   capture   build + run each capture entry, cmp every frame against its baseline
#   manifest  check the baselines against the committed SHA-256 list
#   android   build the arm64 .so
#
# The baselines are the SHA-256 hashes in `docs/baselines3d.sha256`, committed, so a clean
# checkout needs nothing the gate does not generate: the readback harness is
# tests/capture3d/, and the test and Android entries are written by `prepare`. A frame with no
# hash fails. GATE_ADOPT=1 records the hashes the manifest lacks, from this run: deliberate
# re-baselining only, in its own commit, with the reason written down. A hash is a D3D11 claim
# about this machine's driver; another GPU may render other bytes.
#
# Environment:
#   GATE_ADOPT=1           record the hashes docs/baselines3d.sha256 lacks, from this run
#   GATE_SKIP_CAPTURE=1    skip the capture stage (loudly)
#   GATE_SKIP_ANDROID=1    skip the android stage (loudly)
#   GATE_SKIP_BENCH=1      skip the bench stage (loudly)
#   GATE_DEVICE=1          build/run the GLES3 check against whatever adb sees
#   ANDROID_NDK=<path>     NDK root (default: the Windows SDK location)
set -u
cd "$(dirname "$0")/.."
export MSC_NO_GLOBAL_CACHE=1

FAILURES=0
SKIPPED=0
pass() { echo "PASS     $*"; }
fail() { echo "FAIL     $*"; FAILURES=$((FAILURES + 1)); }
skip() { echo "SKIP     $*"; SKIPPED=$((SKIPPED + 1)); }
note() { echo "         $*"; }

TMP=out/tmp
CAPTURE=$TMP/capture
WORK=$TMP/gate3d
SCENE=$TMP/campfireScene.ms
FRAMES="1 6 11 16"

mkdir -p "$WORK" "$CAPTURE/gate"

# Keeps the mtime stable when the content did not change, so msc can stay incremental.
replace_if_changed() {
	if [ -f "$2" ] && diff -q "$1" "$2" > /dev/null 2>&1; then rm -f "$1"; return 0; fi
	mv -f "$1" "$2"
}

# ---- prepare ------------------------------------------------------------------------------
#
# src/examples/campfireScene.ms does not compile on msc 0.2.53 (docs/VOID3D.md, Compiler
# notes): its imports are relative to src/examples, and Math.min/Math.max on two int32 return
# float64. The patched copy every entry builds against is derived here, so it cannot drift
# from the example. The transformation is checked by inverting it: the inverse sed has to
# reproduce the source byte for byte, which is what says nothing else was rewritten.
prepare_scene() {
	if [ ! -f src/examples/campfireScene.ms ]; then
		fail "prepare: src/examples/campfireScene.ms is missing"
		return 1
	fi
	sed -e 's|from "\.\./|from "../../src/|' \
		src/examples/campfireScene.ms > "$WORK/campfireScene.new"
	sed -e 's|from "\.\./\.\./src/|from "../|' \
		"$WORK/campfireScene.new" > "$WORK/campfireScene.back"
	if ! diff --strip-trailing-cr -q src/examples/campfireScene.ms "$WORK/campfireScene.back" > /dev/null; then
		fail "prepare: the patch of campfireScene.ms does not invert cleanly — re-derive it"
		diff --strip-trailing-cr src/examples/campfireScene.ms "$WORK/campfireScene.back" | head -20
		return 1
	fi
	changed=$(diff --strip-trailing-cr src/examples/campfireScene.ms "$WORK/campfireScene.new" | grep -c '^[<>]')
	replace_if_changed "$WORK/campfireScene.new" "$SCENE"
	rm -f "$WORK/campfireScene.back"
	note "prepare: $SCENE patched from the example, $changed lines changed (imports only)"
	return 0
}

# The six capture configurations. Generated rather than kept by hand: out/tmp is gitignored,
# so an entry that lives only there is one bad night away from being lost or silently edited.
#
# Every entry turns the camera snap off. The M2 and M3 baselines were taken before the camera
# had a snap (docs/VOID3D.md, M4 as built); at the campfire's target the snap happens to be a
# no-op, so the images are the same either way, and saying it keeps them that way on purpose.
write_entry() {
	name=$1
	extra=$2
	config=$3
	extraConfig=${4:-}
	outName=${5:-$1}
	{
		echo "// Generated by scripts/gate3d.sh. Edit the script, not this file."
		echo "import {"
		echo "	initCampfire,"
		echo "	frameCampfire,"
		echo "	configureCampfire,"
		echo "	configureCampfireCamera,"
		if [ -n "$extraConfig" ]; then
			echo "$extraConfig" | while IFS= read -r call; do echo "	${call%%(*},"; done
		fi
		echo "} from \"../campfireScene\";"
		echo "import { PixelArtSettings$extra } from \"../../../src/void3d/pixelArtRenderer\";"
		echo "@include(\"../../../src/sokol/bridge.h\");"
		echo "@include(\"capture.h\");"
		echo "@compile(\"./capture.c\");"
		echo "extern function voidRun(w: int32, h: int32, init: () => void, frame: () => void): void;"
		echo "extern function captureSwapchain(frame: int32): void;"
		echo "extern function captureQuit(): void;"
		echo ""
		echo "let frames: int32 = 0;"
		echo ""
		echo "function frame(): void {"
		echo "	frameCampfire();"
		echo "	if (frames == 1 || frames == 6 || frames == 11 || frames == 16) {"
		echo "		captureSwapchain(frames);"
		echo "	}"
		echo "	if (frames == 16) {"
		echo "		captureQuit();"
		echo "	}"
		echo "	frames = frames + 1;"
		echo "}"
		echo ""
		echo "$config"
		[ -n "$extraConfig" ] && echo "$extraConfig"
		echo "configureCampfireCamera(false, 0.0);"
		echo "voidRun(1280, 720, initCampfire, frame);"
	} > "$WORK/$outName.new"
	replace_if_changed "$WORK/$outName.new" "$CAPTURE/$outName.ms"
}

# Everything else the stages read from out/tmp: the readback harness (tracked in tests/capture3d),
# the test entry and the arm64 entry, whose imports are relative to out/tmp.
prepare_harness() {
	mkdir -p "$TMP/android"
	for file in capture.c capture.h; do
		cp "tests/capture3d/$file" "$WORK/$file.new"
		replace_if_changed "$WORK/$file.new" "$CAPTURE/$file"
	done
	echo 'import "../../src/test/index";' > "$WORK/test2d.new"
	replace_if_changed "$WORK/test2d.new" "$TMP/test2d.ms"
	sed -e 's|from "./campfireScene"|from "../campfireScene"|' \
		-e 's|@include("../sokol/|@include("../../../src/sokol/|' \
		src/examples/androidCampfireEntry.ms > "$WORK/androidEntry.new"
	replace_if_changed "$WORK/androidEntry.new" "$TMP/android/campfireEntry.ms"
}

prepare_entries() {
	write_entry campfireCapture "" \
		"configureCampfire(PixelArtSettings.full(), false);"
	write_entry campfirePaletteCapture "" \
		"configureCampfire(PixelArtSettings.full(), true);"
	write_entry campfirePreviewCapture "" \
		"configureCampfire(PixelArtSettings.preview(), true);"
	write_entry campfireDirectCapture "" \
		"configureCampfire({ ...PixelArtSettings.full(), postPass: false }, false);"
	write_entry campfireDepthCapture ", DepthSource" \
		"configureCampfire({ ...PixelArtSettings.full(), depthSource: DepthSource.DepthTexture }, false);"
	# The rebuild-after-context-loss path, against the plain palette-off baseline. Off Android
	# contextGeneration() never moves, so without this the re-upload branch of rebuildMeshes
	# would never execute anywhere: the entry marks every mesh stale at frame 3, and the frames
	# captured after it say whether the rebuilt buffers draw the same pixels.
	write_entry campfireRebuildCapture "" \
		"configureCampfire(PixelArtSettings.full(), false);" \
		"configureCampfireRebuildAt(3);"

	# The seventh configuration is for what the other six cannot reach. They all render a
	# scene placed once that never moves, so none of them exercises a node changing after
	# setup, or a child whose world matrix is its parent's times its own. This one turns the
	# log group every frame. Its baseline is new at M6, which is not the same thing as
	# re-baselining one of the six: those stay byte-identical and a change there is a defect.
	write_bench_entry
	write_pick_entry
	write_entry campfireSpinCapture "" "configureCampfire(PixelArtSettings.full(), false);" "configureCampfireLogSpin(0.11);"

	# Snow and embers on the particle path, the same run with every mesh rebuilt at frame 3, and a
	# palette swapped and a look greyed mid-run, then both put back. The seven above leave
	# particles and the look schedule off.
	write_entry campfireParticlesCapture "" "configureCampfire(PixelArtSettings.full(), false);" \
		"configureCampfireParticles(true);"
	write_entry campfireParticlesRebuildCapture "" \
		"configureCampfire(PixelArtSettings.full(), false);" \
		"configureCampfireParticles(true);
configureCampfireRebuildAt(3);"
	write_entry campfireLookCapture "" "configureCampfire(PixelArtSettings.full(), true);" \
		"configureCampfireLookSchedule(true);"
	# The ground greyed by its own lit material's saturation, with the post pass off and with the
	# palette on, and the same ground greyed in its vertex colours by colorSaturated, which must
	# draw the material's frames byte for byte.
	write_entry campfireGreyDirectCapture "" \
		"configureCampfire({ ...PixelArtSettings.full(), postPass: false }, false);" \
		"configureCampfireGreyGround($GREY_GROUND, false);"
	write_entry campfireGreyCpuCapture "" \
		"configureCampfire({ ...PixelArtSettings.full(), postPass: false }, false);" \
		"configureCampfireGreyGround($GREY_GROUND, true);"
	write_entry campfireGreyPaletteCapture "" "configureCampfire(PixelArtSettings.full(), true);" \
		"configureCampfireGreyGround($GREY_GROUND, false);"
	write_entry campfireForwardCapture "" "configureCampfire(PixelArtSettings.full(), false);" \
		"configureCampfireForward(true);
configureCampfireParticles(true);"
	note "prepare: fourteen capture entries written to $CAPTURE"
}

# msc build answers "Up to date" when only a header a compiled .c includes has changed, and the
# stale code is then linked into the binary with no diagnostic (docs/VOID3D.md, Compiler
# notes). gpu3d.c includes the two shader headers and gpu3d.h; the gate hashes them and evicts what
# was built from them in this checkout's build cache. The machine-wide cache is off for the run.
purge_stale_shader_objects() {
	stamp=$WORK/shaderStamp
	headers="src/void3d/shader3d.glsl.h src/void3d/pixelArt3d.glsl.h src/void3d/gpu3d.h"
	current=$(cat $headers 2>/dev/null | md5sum | cut -d' ' -f1)
	if [ ! -f src/void3d/shader3d.glsl.h ] || [ ! -f src/void3d/pixelArt3d.glsl.h ] ||
		[ ! -f src/void3d/gpu3d.h ]; then
		note "capture: a shader header or gpu3d.h is missing"
		return 0
	fi
	if [ -f "$stamp" ] && [ "$(cat "$stamp")" = "$current" ]; then
		return 0
	fi
	note "capture: a header gpu3d.c includes changed since the last gate — evicting the objects built from it"
	rm -f out/debug/.cache/*gpu3d* out/debug/.cache/*shader3d* out/debug/.cache/*pixelArt3d* 2>/dev/null
	echo "$current" > "$stamp"
}

# ---- entries ------------------------------------------------------------------------------

# msc 0.2.53 on Windows does not call main(): a module that only declares `function main()`
# builds into a binary that exits at once, and under --os=emcc it links the renderer out
# entirely. It has now been the same bug five times — mainSokol2d (fixed in ef1de70), and the
# four void3d entries mainSokol, mainCampfire, iosEntryAnim and iosEmbedEntry. A recurring bug
# class is infrastructure, not a fifth spot fix, so the sixth one fails here instead of
# shipping. Compiler card: 2026-09-20-main-not-called-windows.md.
run_entries() {
	missing=""
	checked=0
	for entry in src/examples/*.ms; do
		grep -qE '^(export )?function main\(' "$entry" || continue
		checked=$((checked + 1))
		grep -qE '^main\(\);' "$entry" || missing="$missing $(basename "$entry")"
	done
	if [ "$checked" -eq 0 ]; then
		skip "entries: no entry point declares main(), so there was nothing to check"
		return
	fi
	if [ -n "$missing" ]; then
		fail "entries: declared main() with no top-level call:$missing"
		echo "         each of those builds a binary that exits at once — add \`main();\` at the end"
		return
	fi
	broken=""
	for entry in src/examples/*.ms; do
		grep -qE '^(export )?function main\(' "$entry" || continue
		case "$(basename "$entry")" in
			ios*|android*) continue ;;
		esac
		msc build "$entry" > "$WORK/entry-build.log" 2>&1 || broken="$broken $(basename "$entry")"
	done
	if [ -n "$broken" ]; then
		fail "entries: declared main() and calls it, but does not build:$broken"
		tail -4 "$WORK/entry-build.log" | sed 's/^/         /'
		return
	fi
	pass "entries: $checked entry points declare main() and call it; the host ones build"
}

# ---- shaders ------------------------------------------------------------------------------
#
# REVIEWS-3D M6 defect 12: nothing checked that a .glsl.h was regenerated from its .glsl, and
# the M7 light block made the generated header load-bearing. shdc echoes the output path into
# the header twice (the Cmdline comment, the include-guard #error), so both lines are dropped
# and the comparison is then byte-exact.
run_shaders() {
	case "$(uname -s)-$(uname -m)" in
		Darwin-arm64)  SHDC="deps/sokol-tools-bin/bin/osx_arm64/sokol-shdc" ;;
		Darwin-*)      SHDC="deps/sokol-tools-bin/bin/osx/sokol-shdc" ;;
		Linux-aarch64) SHDC="deps/sokol-tools-bin/bin/linux_arm64/sokol-shdc" ;;
		Linux-*)       SHDC="deps/sokol-tools-bin/bin/linux/sokol-shdc" ;;
		*)             SHDC="deps/sokol-tools-bin/bin/win32/sokol-shdc.exe" ;;
	esac
	if [ ! -f "$SHDC" ]; then
		skip "shaders: sokol-shdc not found — .glsl.h freshness not checked"
		return
	fi
	SHDC_LANGS="metal_macos:glsl300es:wgsl:hlsl5"
	SHDC_LANGS_IOS="metal_macos:metal_ios:metal_sim:glsl300es:wgsl:hlsl5"
	for SHDC_SRC in src/sokol/shader.glsl src/void2d/shader2d.glsl src/void3d/shader3d.glsl \
		src/void3d/pixelArt3d.glsl; do
		SHDC_LANGS_PICK="$SHDC_LANGS"
		case "$SHDC_SRC" in
			src/sokol/*|src/void3d/*) SHDC_LANGS_PICK="$SHDC_LANGS_IOS" ;;
		esac
		SHDC_OUT="$WORK/fresh_$(basename "$SHDC_SRC" .glsl).h"
		if ! "$SHDC" -i "$SHDC_SRC" -o "$SHDC_OUT" -l "$SHDC_LANGS_PICK" -f sokol >/dev/null 2>&1; then
			fail "shaders: sokol-shdc failed on $SHDC_SRC"
			return
		fi
		sed -e '/^        sokol-shdc /d' -e '/Please include sokol_gfx.h before/d' "$SHDC_OUT" > "$SHDC_OUT.n"
		sed -e '/^        sokol-shdc /d' -e '/Please include sokol_gfx.h before/d' "$SHDC_SRC.h" > "$SHDC_SRC.h.n"
		if cmp -s "$SHDC_OUT.n" "$SHDC_SRC.h.n"; then
			pass "shaders: $SHDC_SRC.h is a fresh regeneration of its .glsl"
		else
			fail "shaders: $SHDC_SRC.h is stale — run scripts/regen-shaders.sh and commit it"
		fi
		rm -f "$SHDC_OUT" "$SHDC_OUT.n" "$SHDC_SRC.h.n"
	done
}

# The bench entry: warm up, measure, print machine-readable rows, quit. It reuses the capture
# harness's quit because that is what lets a windowed run end by itself.
write_bench_entry() {
	{
		echo "// Generated by scripts/gate3d.sh. Edit the script, not this file."
		echo "import {"
		echo "	initCampfire,"
		echo "	frameCampfire,"
		echo "	configureCampfire,"
		echo "	configureCampfireCamera,"
		echo "	configureCampfireLogSpin,"
		echo "	configureCampfireParticles,"
		echo "	campfireStats,"
		echo "	CampfireStats,"
		echo "} from \"../campfireScene\";"
		echo "import { PixelArtSettings } from \"../../../src/void3d/pixelArtRenderer\";"
		echo "@include(\"../../../src/sokol/bridge.h\");"
		echo "@include(\"capture.h\");"
		echo "@compile(\"./capture.c\");"
		echo "extern function voidRun(w: int32, h: int32, init: () => void, frame: () => void): void;"
		echo "extern function captureQuit(): void;"
		echo ""
		echo "const WARMUP: int32 = $BENCH_WARMUP;"
		echo "const MEASURED: int32 = $BENCH_FRAMES;"
		echo "let frames: int32 = 0;"
		echo "let started: float64 = 0.0;"
		echo "let cpu: float64 = 0.0;"
		echo "let base: CampfireStats = { drawItems: 0, nodes: 0, meshes: 0, rebuildable: 0, pipelines: 0, uniforms: 0, stack: 0 };"
		echo ""
		echo "function frame(): void {"
		echo "	const enter: float64 = performance.now();"
		echo "	frameCampfire();"
		echo "	const left: float64 = performance.now();"
		echo "	if (frames >= WARMUP) { cpu = cpu + (left - enter); }"
		echo "	frames = frames + 1;"
		echo "	if (frames == WARMUP) {"
		echo "		base = campfireStats();"
		echo "		started = performance.now();"
		echo "	}"
		echo "	if (frames == WARMUP + MEASURED) {"
		echo "		const elapsed: float64 = performance.now() - started;"
		echo "		const now: CampfireStats = campfireStats();"
		echo "		console.log(\`BENCH campfire.drawItems \${now.drawItems}\`);"
		echo "		console.log(\`BENCH campfire.nodes \${now.nodes}\`);"
		echo "		console.log(\`BENCH campfire.meshes \${now.meshes}\`);"
		echo "		console.log(\`BENCH campfire.rebuildable \${now.rebuildable}\`);"
		echo "		console.log(\`BENCH campfire.pipelines \${now.pipelines}\`);"
		echo "		console.log(\`BENCH growth.drawItems \${now.drawItems - base.drawItems}\`);"
		echo "		console.log(\`BENCH growth.nodes \${now.nodes - base.nodes}\`);"
		echo "		console.log(\`BENCH growth.meshes \${now.meshes - base.meshes}\`);"
		echo "		console.log(\`BENCH growth.pipelines \${now.pipelines - base.pipelines}\`);"
		echo "		console.log(\`BENCH growth.uniforms \${now.uniforms - base.uniforms}\`);"
		echo "		console.log(\`BENCH growth.stack \${now.stack - base.stack}\`);"
		echo "		console.log(\`BENCH time.cpuMsPerFrame \${cpu / (MEASURED as float64)}\`);"
		echo "		console.log(\`BENCH time.wallMsPerFrame \${elapsed / (MEASURED as float64)}\`);"
		echo "		captureQuit();"
		echo "	}"
		echo "}"
		echo ""
		echo "configureCampfire(PixelArtSettings.full(), false);"
		echo "configureCampfireCamera(false, 0.0);"
		echo "configureCampfireLogSpin(0.11);"
		echo "configureCampfireParticles(true);"
		echo "voidRun(1280, 720, initCampfire, frame);"
	} > "$WORK/campfireBench.new"
	replace_if_changed "$WORK/campfireBench.new" "$CAPTURE/campfireBench.ms"
}

# Taps through the view and blit the renderer drew with: a snapping, panning camera with a
# margin, so the blit carries a remainder, and the logs turning. Each tap is aimed with
# `project` through that same pair, so a mapping error both share passes; nothing reads pixels.
write_pick_entry() {
	{
		echo "// Generated by scripts/gate3d.sh. Edit the script, not this file."
		echo "import {"
		echo "	initCampfire,"
		echo "	frameCampfire,"
		echo "	configureCampfire,"
		echo "	configureCampfireCamera,"
		echo "	configureCampfireLogSpin,"
		echo "	campfireTargets,"
		echo "	campfirePixelOf,"
		echo "	campfireTap,"
		echo "	CampfireTargets,"
		echo "} from \"../campfireScene\";"
		echo "import { PixelArtSettings } from \"../../../src/void3d/pixelArtRenderer\";"
		echo "import { NodeId, SceneError } from \"../../../src/void3d/scene\";"
		echo "import { PickHit, PickError } from \"../../../src/void3d/pick\";"
		echo "import { Vec3 } from \"../../../src/math/math3d\";"
		echo "@include(\"../../../src/sokol/bridge.h\");"
		echo "@include(\"capture.h\");"
		echo "@compile(\"./capture.c\");"
		echo "extern function voidRun(w: int32, h: int32, init: () => void, frame: () => void): void;"
		echo "extern function captureQuit(): void;"
		echo ""
		echo "let frames: int32 = 0;"
		echo ""
		echo "function tap(label: string, on: NodeId, owner: NodeId, expectHit: boolean): void {"
		echo "	const aimed: Result<Vec3, SceneError> = campfirePixelOf(on);"
		echo "	if (!aimed.ok) {"
		echo "		console.log(\`PICK \${label} FAIL the target is not a live mesh node\`);"
		echo "		return;"
		echo "	}"
		echo "	const at: Vec3 = aimed.value;"
		echo "	const x: float32 = Math.floor(at.x) + 0.5;"
		echo "	const y: float32 = Math.floor(at.y) + 0.5;"
		echo "	const picked: Result<PickHit, PickError> = campfireTap(x, y);"
		echo "	if (!picked.ok) {"
		echo "		const verdict: string = expectHit ? \"FAIL\" : \"PASS\";"
		echo "		console.log(\`PICK \${label} \${verdict} pixel=(\${x}, \${y}) nothing hit\`);"
		echo "		return;"
		echo "	}"
		echo "	const hit: PickHit = picked.value;"
		echo "	const right: boolean = expectHit && hit.owner.index == owner.index &&"
		echo "		hit.owner.generation == owner.generation;"
		echo "	const verdict: string = right ? \"PASS\" : \"FAIL\";"
		echo "	const where: string = \`pixel=(\${x}, \${y}) owner=\${hit.owner.index}\`;"
		echo "	const what: string = \`mesh=\${hit.mesh.index} distance=\${hit.distance}\`;"
		echo "	console.log(\`PICK \${label} \${verdict} \${where} \${what}\`);"
		echo "}"
		echo ""
		echo "function frame(): void {"
		echo "	frameCampfire();"
		echo "	frames = frames + 1;"
		echo "	if (frames == $PICK_FRAME) {"
		echo "		const targets: CampfireTargets = campfireTargets();"
		echo "		tap(\"logs\", targets.firstLog, targets.logs, true);"
		echo "		tap(\"bakedStone\", targets.bakedStone, targets.bakedStone, true);"
		echo "		tap(\"plainStone\", targets.plainStone, targets.plainStone, false);"
		echo "		captureQuit();"
		echo "	}"
		echo "}"
		echo ""
		echo "configureCampfire({ ...PixelArtSettings.full(), margin: 1 }, false);"
		echo "configureCampfireCamera(true, 0.3);"
		echo "configureCampfireLogSpin(0.11);"
		echo "voidRun(1280, 720, initCampfire, frame);"
	} > "$WORK/campfirePick.new"
	replace_if_changed "$WORK/campfirePick.new" "$CAPTURE/campfirePick.ms"
}

# ---- pick ---------------------------------------------------------------------------------

run_pick() {
	if [ ! -f "$CAPTURE/capture.c" ] || [ ! -f "$CAPTURE/capture.h" ]; then
		skip "pick: $CAPTURE/capture.c and capture.h are missing (gitignored out/tmp harness)"
		return
	fi
	if ! msc build "$CAPTURE/campfirePick.ms" > "$WORK/pick-build.log" 2>&1; then
		fail "pick: the pick entry did not build"
		tail -5 "$WORK/pick-build.log" | sed 's/^/         /'
		return
	fi
	if ! "./out/debug/campfirePick.exe" > "$WORK/pick.log" 2>&1; then
		fail "pick: the pick run did not finish"
		tail -5 "$WORK/pick.log" | sed 's/^/         /'
		return
	fi
	rows=$(grep -c '^PICK ' "$WORK/pick.log" || true)
	wrong=$(grep -c '^PICK [a-zA-Z]* FAIL' "$WORK/pick.log" || true)
	if [ "$rows" -ne 3 ] || [ "$wrong" -ne 0 ]; then
		fail "pick: $wrong of $rows tap(s) on the campfire picked the wrong thing (3 expected)"
		grep '^PICK ' "$WORK/pick.log" | sed 's/^/         /'
		return
	fi
	pass "pick: 3 taps aimed through the campfire's drawn view, snapping and panning, picked right"
	grep '^PICK ' "$WORK/pick.log" | sed 's/^PICK /         pick: /'
}

# ---- bench --------------------------------------------------------------------------------

# Counters gate hard and milliseconds only report. The counters here are the lengths of every
# piece of frame state, and a growth of anything but zero means a steady frame allocated —
# which "Frame state is preallocated... nothing in `frame` allocates" says it must not.
#
# There is deliberately no millisecond threshold. A wall-clock gate needs the run-to-run
# variance measured first, and a threshold tighter than that variance is a false alarm every
# other run, which ends with the gate being switched off. The number is printed so it can be
# watched; docs/VOID3D.md records the variance when it has been taken over enough runs.
run_bench() {
	if [ "${GATE_SKIP_BENCH:-0}" = "1" ]; then
		skip "bench: GATE_SKIP_BENCH=1 — frame-state growth was not measured"
		return
	fi
	if [ ! -f "$CAPTURE/campfireBench.ms" ]; then
		skip "bench: $CAPTURE/campfireBench.ms is missing"
		return
	fi
	if ! msc build "$CAPTURE/campfireBench.ms" --release > "$WORK/bench-build.log" 2>&1; then
		fail "bench: the bench entry did not build"
		tail -5 "$WORK/bench-build.log" | sed 's/^/         /'
		return
	fi
	if ! "./out/release/campfireBench.exe" > "$WORK/bench.log" 2>&1; then
		fail "bench: the bench run did not finish"
		tail -5 "$WORK/bench.log" | sed 's/^/         /'
		return
	fi
	rows=$(grep -c '^BENCH ' "$WORK/bench.log" || true)
	if [ "$rows" -eq 0 ]; then
		fail "bench: the run produced no BENCH rows"
		return
	fi
	grew=""
	for row in $(grep '^BENCH growth\.' "$WORK/bench.log" | awk '{print $2 "=" $3}'); do
		case "$row" in
			*=0) ;;
			*) grew="$grew $row" ;;
		esac
	done
	if [ -n "$grew" ]; then
		fail "bench: frame state grew during a steady run — the frame allocated:$grew"
		return
	fi
	cpu=$(grep '^BENCH time.cpuMsPerFrame' "$WORK/bench.log" | awk '{print $3}')
	wall=$(grep '^BENCH time.wallMsPerFrame' "$WORK/bench.log" | awk '{print $3}')
	counts=$(grep '^BENCH campfire\.' "$WORK/bench.log" | awk '{printf "%s=%s ", substr($2,10), $3}')
	pass "bench: no frame-state growth over $BENCH_FRAMES frames; $counts"
	note "bench: ${cpu} ms of CPU per frame; wall clock ${wall} ms is vsync-bound, not a cost"
	note "bench: reported only — docs/VOID3D.md records the variance behind any future threshold"
}

# ---- device -------------------------------------------------------------------------------

# The GLES3 backend is the one Hibernal ships on and the one with no byte-level numbers. It ran
# for the first time before M7 (tests/device/gles3Campfire.png) — on the Android emulator, which
# is not a device. This stage is a loud SKIP by default rather than a silent omission: a green
# gate should say out loud that the shipping backend is unverified here, the way the baseline
# skips do. GATE_DEVICE=1 builds, installs and runs it against whatever adb can see.
run_device() {
	if [ "${GATE_DEVICE:-0}" != "1" ]; then
		skip "device: GATE_DEVICE=1 not set — no GLES3 run this gate; every pixel claim here is D3D11 only"
		return
	fi
	adb=${ADB:-$HOME/AppData/Local/Android/Sdk/platform-tools/adb.exe}
	if [ ! -x "$adb" ] && ! command -v adb > /dev/null 2>&1; then
		skip "device: no adb (set ADB)"
		return
	fi
	[ -x "$adb" ] || adb=adb
	target=$("$adb" devices | awk 'NR>1 && $2=="device" { print $1; exit }')
	if [ -z "$target" ]; then
		skip "device: adb sees no device"
		return
	fi
	kind=$("$adb" -s "$target" shell getprop ro.build.characteristics | tr -d '
')
	egl=$("$adb" -s "$target" shell getprop ro.hardware.egl | tr -d '
')
	if ! "$adb" -s "$target" shell pidof com.metascript.voidsample > /dev/null 2>&1; then
		skip "device: $target ($kind, egl=$egl) is there but the app is not running — see tests/device/README.md"
		return
	fi
	"$adb" -s "$target" exec-out screencap -p > "$WORK/device.png" 2>/dev/null
	colours=$(magick "$WORK/device.png" -format "%k" info: 2>/dev/null || echo 0)
	# A palette quantizes a real frame to a couple of dozen colours, so the count alone cannot
	# tell it from a blank one; a blank frame is one colour over nearly every pixel.
	dominant=$(magick "$WORK/device.png" -format %c histogram:info: 2>/dev/null |
		awk '{ n = $1 + 0; t += n; if (n > m) m = n } END { if (t) printf "%d", 100 * m / t; else print 100 }')
	if [ "$colours" -lt 8 ] || [ "$dominant" -gt 90 ]; then
		fail "device: $target rendered $colours colours, one of them over $dominant% of the frame — blank or near-blank"
		return
	fi
	pass "device: $target ($kind, egl=$egl) rendering, $colours colours, largest $dominant% — NOT a baseline comparison"
}

# ---- oracle -------------------------------------------------------------------------------

# Heaps is the reference for everything this port copies, and until scripts/oracle.sh existed
# every claim about what Heaps does rested on somebody having read the file. This runs the
# port's side of tests/oracle/*.cases against a snapshot taken from real Heaps and committed,
# so an ordinary gate needs no Haxe. `sh scripts/oracle.sh regen <cases>` retakes the snapshot
# and is the only part that does. Every file in that directory is checked, so adding a case
# file needs no edit here — which is how it was written when only bounds3d existed, and
# scene3d would then have been added and silently never run.
run_oracle() {
	found=0
	agreed=0
	diverged=0
	for cases in tests/oracle/*.cases; do
		[ -f "$cases" ] || continue
		found=$((found + 1))
		snapshot=${cases%.cases}.snapshot
		if [ ! -f "$snapshot" ]; then
			skip "oracle: no snapshot for $cases — run 'sh scripts/oracle.sh regen $cases' with Haxe"
			return
		fi
		if sh scripts/oracle.sh check "$cases" > "$WORK/oracle.log" 2>&1; then
			agreed=$((agreed + $(grep -c '^AGREES' "$WORK/oracle.log")))
			diverged=$((diverged + $(grep -c '^DIVERGES' "$WORK/oracle.log")))
		else
			fail "oracle: $cases and real Heaps disagree in a way nothing declared"
			grep -E '^(MISMATCH|GRADUATED|MISSING)' "$WORK/oracle.log" | head -8 | sed 's/^/         /'
			return
		fi
	done
	if [ "$found" = 0 ]; then
		skip "oracle: no tests/oracle/*.cases to check"
		return
	fi
	pass "oracle: $agreed case(s) agree with real Heaps and $diverged diverge as declared, over $found file(s)"
}

