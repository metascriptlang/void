# ---- pending ------------------------------------------------------------------------------

# tests/PENDING3D.md on rexa's rule: a listed case that stops holding fails the run, and its row
# is deleted in the same commit as the fix. Enforced in both directions, because a list with a
# forcing function in only one direction rots from the other end.
#
# What this stage sees is that a **sentinel is present**, not that the **divergence still
# holds** — measured: fixing `size()` while leaving its `// PENDING3D:` line in place passes
# here and fails `oracle`. Only the rows with a `diverges=` oracle case are enforced
# behaviourally; tests/PENDING3D.md names them. The `*)` branch
# below is deliberately a requirement and not a skip: a row naming a sentinel nobody wrote
# fails rather than passing quietly.
run_pending() {
	if [ ! -f "$PENDING" ]; then
		skip "pending: $PENDING is missing, so nothing holds the known divergences to account"
		return
	fi
	if ! sh scripts/testCapturePending.sh > "$WORK/capture-pending-controls.log" 2>&1; then
		fail "capture pending protocol controls — see $WORK/capture-pending-controls.log"
		return
	fi
	pass "capture pending: exact held bytes, unknown-byte rejection and stale-row controls"
	keys=$(capture_pending_keys "$PENDING") || { fail "pending: unreadable capture records"; return; }
	for key in $keys; do
		old=$(expected_hash "$key")
		verdict=$(capture_pending_verdict "$PENDING" "$key" "$old" "") || verdict=invalid
		if [ "$verdict" != "listed" ]; then
			fail "pending: orphan, duplicate or invalid capture fingerprint $key"
			return
		fi
	done
	rows=$(grep -oE '^\| `[a-z0-9-]+`' "$PENDING" | tr -d '|` ' | sort)
	tags=$(grep -rhoE 'PENDING3D: [a-z0-9-]+' src/ | sed 's/PENDING3D: //' | sort -u)
	graduated=""
	for row in $rows; do
		case "$row" in
			baselines-adopted-circular)
				grep -q 'plausible\* M4 images' docs/VOID3D.md || graduated="$graduated $row" ;;
			gles3-emulator-only)
				grep -q 'not a device' docs/VOID3D.md || graduated="$graduated $row" ;;
			capture-m14forward|capture-m16anchor)
				grep -qF "$row" docs/VOID3D.md || graduated="$graduated $row"
				for frame in $FRAMES; do
					key="${row#capture-}_$frame.ppm"
					old=$(expected_hash "$key")
					verdict=$(capture_pending_verdict "$PENDING" "$key" "$old" "") || verdict=invalid
					if [ "$verdict" != "listed" ]; then
						fail "pending: $row has missing, duplicate or invalid hash data for $key"
						return
					fi
				done ;;
			*)
				echo "$tags" | grep -qx "$row" || graduated="$graduated $row" ;;
		esac
	done
	unlisted=""
	for tag in $tags; do
		echo "$rows" | grep -qx "$tag" || unlisted="$unlisted $tag"
	done
	if [ -n "$graduated" ]; then
		fail "pending: listed but no longer holding — delete the row in the commit that fixed it:$graduated"
		return
	fi
	if [ -n "$unlisted" ]; then
		fail "pending: marked in the tree with no row in $PENDING:$unlisted"
		return
	fi
	count=$(echo "$rows" | grep -c .)
	pass "pending: $count rows in $PENDING, every sentinel present and every sentinel listed"
}

