# $1 entry, $2 label, $3 the module:function list. Prints nothing and returns 0 when clean;
# otherwise records the failure and returns 1.
check_array_copies() {
	rm -f out/debug/*ZsrcZgpuZ*Oms.c out/debug/*ZsrcZvoid3dZ*Oms.c "out/debug/$(basename "$1" .ms).exe"
	if ! msc build "$1" --emit=c > "$WORK/allocation.log" 2>&1; then
		fail "allocation: emitting C for $1 failed; see $WORK/allocation.log"
		return 1
	fi
	offenders=""
	builders=""
	for entry in $3; do
		module=${entry%%:*}
		fn=${entry#*:}
		emitted=$(ls out/debug/*ZsrcZvoid3dZ${module}Oms.c out/debug/*ZsrcZgpuZ${module}Oms.c 2>/dev/null | head -1)
		if [ -z "$emitted" ] || ! grep -q "^[a-zA-Z_].*[^a-zA-Z0-9_]${fn}__M.*{[[:space:]]*$" "$emitted"; then
			fail "allocation: the emitted C of $module.ms has no body for $fn — renamed or unreachable?"
			return 1
		fi
		body=$(awk "/^[a-zA-Z_].*\y${fn}__M.*\{[ \t]*\$/,/^}/" "$emitted")
		copies=$(echo "$body" | grep -c 'ArrayCopy(' || true)
		[ "$copies" -gt 0 ] && offenders="$offenders ${fn}=${copies}"
		strings=$(echo "$body" | grep -cE 'msStringConcat|msNumberToString|toString__M' || true)
		[ "$strings" -gt 0 ] && builders="$builders ${fn}=${strings}"
	done
	if [ -n "$offenders" ]; then
		fail "allocation: the $2 copies an array — ArrayCopy in:$offenders"
		echo "         CODE-STYLE section 5, the copy trap: index the field or take a Span view"
		return 1
	fi
	if [ -n "$builders" ]; then
		fail "allocation: the $2 builds a string:$builders"
		echo "         a message belongs in a function only the stopping path calls (scene.ms stopOnDeadId)"
		return 1
	fi
	return 0
}

