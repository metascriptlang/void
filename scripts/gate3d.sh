# ---- capture ------------------------------------------------------------------------------
#
# One configuration: rebuild the entry, run it, and hash all four frames against the baseline
# it claims to reproduce. The committed docs/baselines3d.sha256 *is* the baseline set, so a
# clean checkout has everything the comparison needs, and a frame with no hash there fails.
# The binary is deleted first so the link is always redone; the object eviction above is what
# makes a stale shader impossible.
#
# A frame that matches is also kept as out/tmp/capture/<baseline>_<frame>.ppm. That copy is
# only ever read to measure a later difference (AE, PAE); it decides nothing.
expected_hash() {
	tr -d '\r' < "$MANIFEST" | sed -n "s|^\([0-9a-f]\{64\}\) \*$1\$|\1|p" | head -1
}

baseline_names() {
	for prefix in before m3palette m3preview m3direct m3depth m6spin m11particles m11look \
		m12greydirect m12greypalette m14forward m16anchor m21perspective m22textured \
		m22texturedpixelart m22texturedoutline m23gltf m23gltfpixelart; do
		for frame in $FRAMES; do
			echo "${prefix}_$frame.ppm"
		done
	done
}

# GATE_ADOPT=1 only: writes the hash of a baseline the manifest does not have yet, keeping the
# manifest in baseline_names order.
record_hash() {
	if ! baseline_names | grep -qx "$1"; then
		fail "capture: $1 is not in baseline_names, so the manifest would drop its hash"
		return 1
	fi
	tr -d '\r' < "$MANIFEST" | grep -v " \*$1\$" > "$WORK/manifest.old"
	echo "$2 *$1" >> "$WORK/manifest.old"
	: > "$WORK/manifest.new"
	for key in $(baseline_names); do
		grep " \*$key\$" "$WORK/manifest.old" >> "$WORK/manifest.new" || true
	done
	cp "$WORK/manifest.new" "$MANIFEST"
}

build_and_capture() {
	name=$1
	entry=$CAPTURE/$name.ms
	if [ ! -f "$entry" ]; then
		fail "capture $name: the entry is missing"
		return 1
	fi
	rm -f "out/debug/$name.exe" "$CAPTURE/gate/${name}_"*.ppm
	if ! msc build "$entry" > "$WORK/$name.build.log" 2>&1; then
		fail "capture $name: build failed"
		tail -30 "$WORK/$name.build.log"
		return 1
	fi
	if [ ! -f "out/debug/$name.exe" ]; then
		fail "capture $name: out/debug/$name.exe was not produced"
		return 1
	fi
	if ! CAPTURE_PREFIX="$CAPTURE/gate/$name" "./out/debug/$name.exe" > "$WORK/$name.run.log" 2>&1; then
		rm -f "$CAPTURE/gate/${name}_"*.ppm
		fail "capture $name: the run exited nonzero"
		tail -20 "$WORK/$name.run.log"
		return 1
	fi
	return 0
}

run_capture() {
	name=$1
	baseline=$2
	what=$3
	build_and_capture "$name" || return
	missing=0
	differing=0
	adopted=0
	held=0
	for frame in $FRAMES; do
		got=$CAPTURE/gate/${name}_$frame.ppm
		key=${baseline}_$frame.ppm
		want=$CAPTURE/$key
		if [ ! -f "$got" ]; then
			fail "capture $name: frame $frame was not captured"
			return
		fi
		hash=$(sha256sum "$got" | cut -d' ' -f1)
		expected=$(expected_hash "$key")
		verdict=$(capture_pending_verdict "$PENDING" "$key" "$expected" "$hash") || verdict=invalid
		case "$verdict" in
			held) held=$((held + 1)); continue ;;
			stale)
				fail "capture $name: row stale: remove capture-$baseline (frame $frame returned to M26)"
				return ;;
			mismatch)
				fail "capture $name: frame $frame changed its held 0.3.0 fingerprint"
				return ;;
			invalid)
				fail "capture $name: invalid PENDING3D hash record for $key"
				return ;;
			normal) ;;
			*) fail "capture $name: unknown pending verdict $verdict"; return ;;
		esac
		if [ -z "$expected" ]; then
			if [ "${GATE_ADOPT:-0}" = "1" ]; then
				record_hash "$key" "$hash" || return
				cp "$got" "$want"
				adopted=$((adopted + 1))
			else
				missing=$((missing + 1))
			fi
			continue
		fi
		if [ "$hash" = "$expected" ]; then
			cmp -s "$got" "$want" 2>/dev/null || cp "$got" "$want"
			continue
		fi
		differing=$((differing + 1))
		note "capture $name: frame $frame does not hash to $key in $MANIFEST"
		if [ -f "$want" ] && [ "$(sha256sum "$want" | cut -d' ' -f1)" = "$expected" ] &&
			command -v magick > /dev/null 2>&1; then
			absolute=$(magick compare -metric AE "$want" "$got" null: 2>&1 | tail -1)
			peak=$(magick compare -metric PAE "$want" "$got" null: 2>&1 | tail -1)
			note "capture $name: frame $frame AE $absolute, PAE $peak"
		else
			note "capture $name: no local image of $key to measure the difference against"
		fi
	done
	if [ "$differing" -gt 0 ]; then
		fail "capture $name ($what): $differing of 4 frames differ from ${baseline}_*.ppm"
	elif [ "$missing" -gt 0 ]; then
		fail "capture $name ($what): $missing of 4 frames have no ${baseline}_* hash in $MANIFEST (GATE_ADOPT=1 records them)"
	elif [ "$adopted" -gt 0 ]; then
		skip "capture $name ($what): recorded $adopted new ${baseline}_* hashes in $MANIFEST — commit them, and write down why"
	elif [ "$held" -gt 0 ]; then
		skip "capture $name: $held exact 0.3.0 fingerprints held, not accepted — capture-$baseline"
	else
		pass "capture $name ($what): 4 frames byte-identical to ${baseline}_*.ppm"
	fi
}

# The look schedule swaps the palette and greys the look, then puts both back before frame 16,
# and frame 1 is before any of it: both have to be the palette-on image, byte for byte. A swap
