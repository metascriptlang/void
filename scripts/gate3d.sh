		return
	fi
	ratios=$(echo "$ground $luma $GREY_GROUND" | awk '
		function dec(x) {
			return x <= 0.04045 ? x * 0.0773993808 : exp(log(x * 0.9478672986 + 0.0521327014) * 2.4)
		}
		{
			l = $1 * $4 + $2 * $5 + $3 * $6
			for (i = 1; i <= 3; i++) printf "%.9f ", dec($i * (1 + $7) - l * $7) / dec($i)
		}')
	for frame in $FRAMES; do
		plain=$CAPTURE/gate/campfireDirectCapture_$frame.ppm
		greyed=$CAPTURE/gate/campfireGreyDirectCapture_$frame.ppm
		if [ ! -f "$plain" ] || [ ! -f "$greyed" ]; then
			fail "multiply: frame $frame of campfireDirectCapture or campfireGreyDirectCapture was not captured"
			return
		fi
		set -- $(count_off_ratio "$plain" "$greyed" $ratios)
		if [ "$2" -eq 0 ]; then
			fail "multiply: frame $frame has no ground pixel that greying changed"
			return
		fi
		if [ "$(($2 - $3))" -le 0 ]; then
			fail "multiply: frame $frame, every ground pixel the greying changed clips at 255, so the ratio is verified nowhere"
			return
		fi
		if [ "$1" -ne 0 ]; then
			fail "multiply: frame $frame, $1 of $2 ground pixels are not the plain ground's linear light × grey/ground ($3 of them clip at 255)"
			return
		fi
	done
	pass "multiply: the greyed ground is the plain ground's linear light × grey/ground ($ratios) in 4 frames"
}

# The forward flame is an unlit billboard of colour 1, so its atlas texels reach the frame
# unchanged: each of its three colours must be there. None of them is in the forward frame
# without billboards (measured on the pre-M15 m14forward frames: 0 pixels of each).
run_unlit_billboard() {
	colours=$(sed -n 's/.*setTexturePixel(width, cellLeft + x, y, \([0-9]*\), \([0-9]*\), \([0-9]*\));/\1,\2,\3/p' \
		src/examples/campfireScene.ms)
	if [ "$(echo $colours | wc -w)" -ne 3 ]; then
		fail "unlit: the flame's three texel colours were not found in campfireScene.ms (got '$colours')"
		return
	fi
	counts=""
	for frame in $FRAMES; do
		got=$CAPTURE/gate/campfireForwardCapture_$frame.ppm
		if [ ! -f "$got" ]; then
			fail "unlit: frame $frame of campfireForwardCapture was not captured"
			return
		fi
		for colour in $colours; do
			n=$(magick "$got" -fill black +opaque "rgb($colour)" -fill white -opaque "rgb($colour)" \
				-format "%[fx:round(mean*w*h)]" info:)
			if [ "$n" -eq 0 ]; then
				fail "unlit: frame $frame of the forward capture has no pixel of the flame texel rgb($colour)"
				return
			fi
			counts="$counts $n"
		done
	done
	pass "unlit: the forward flame writes its 3 texel colours unchanged in 4 frames (pixels:$counts)"
}

# Every other capture anchors across the centre, so only this one sees a sign or axis slip in
# `corner - anchor`: bottom left moves the flame right at both edges by one shift, rows fixed.
flame_box() {
	image=$1
	shift
	for colour in "$@"; do
		magick "$image" -fill black +opaque "rgb($colour)" -fill white -opaque "rgb($colour)" \
			-format "%@\n" info:
	done | awk -F'[x+]' '$1 > 0 {
		if (!seen || $3 < left) left = $3
		if (!seen || $3 + $1 > right) right = $3 + $1
		if (!seen || $4 < top) top = $4
		if (!seen || $4 + $2 > bottom) bottom = $4 + $2
		seen = 1
	} END { if (seen) print left, right, top, bottom }'
}

run_anchor_moves_flame() {
	colours=$(sed -n 's/.*setTexturePixel(width, cellLeft + x, y, \([0-9]*\), \([0-9]*\), \([0-9]*\));/\1,\2,\3/p' \
		src/examples/campfireScene.ms)
	shifts=""
	for frame in $FRAMES; do
		centred=$CAPTURE/gate/campfireForwardCapture_$frame.ppm
		anchored=$CAPTURE/gate/campfireAnchorCapture_$frame.ppm
		if [ ! -f "$centred" ] || [ ! -f "$anchored" ]; then
			fail "anchor: frame $frame of campfireForwardCapture or campfireAnchorCapture was not captured"
			return
		fi
		set -- $(flame_box "$centred" $colours) $(flame_box "$anchored" $colours)
		if [ $# -ne 8 ]; then
			fail "anchor: frame $frame, the flame's texels were not found in both frames"
			return
		fi
		dxLeft=$(($5 - $1))
		dxRight=$(($6 - $2))
		if [ "$7" -ne "$3" ] || [ "$8" -ne "$4" ]; then
			fail "anchor: frame $frame, the flame's rows moved from $3..$4 to $7..$8"
			return
		fi
		if [ "$dxLeft" -le 0 ] || [ "$dxRight" -le 0 ] || [ $((dxLeft - dxRight)) -gt 1 ] ||
			[ $((dxRight - dxLeft)) -gt 1 ]; then
			fail "anchor: frame $frame, the flame's edges moved by $dxLeft and $dxRight pixels, not one shift right"
			return
		fi
		shifts="$shifts $dxLeft"
	done
	pass "anchor: a bottom-left anchor moves the forward flame right by one shift, rows unchanged (pixels:$shifts)"
}

# No hash of its own: what the HUD frame must be follows from campfireCapture, so void2d's pixels
# stay a claim of void2d's gate. Outside the HUD it is campfireCapture byte for byte, the opaque bar
# is its colour exactly, and the half-transparent black panel is half of what lies under it,
# within 1 per channel: the claim is the composition, not the GPU's rounding of a half.
HUD_BAR="320x32+40+40"
HUD_PANEL="1200x90+40+600"

# $1 the frame without the HUD, $2 with it. Prints what is wrong, or nothing.
hud_mismatch() {
	magick "$1" -fill black -draw "rectangle 40,40 359,71" -draw "rectangle 40,600 1239,689" \
		"$WORK/hudUnder.ppm"
	magick "$2" -fill black -draw "rectangle 40,40 359,71" -draw "rectangle 40,600 1239,689" \
		"$WORK/hudOver.ppm"
	outside=$(magick compare -metric AE "$WORK/hudUnder.ppm" "$WORK/hudOver.ppm" null: 2>&1 |
		tail -1 | cut -d' ' -f1)
	if [ "$outside" != "0" ]; then
		echo "$outside pixels outside the HUD differ from the campfire without it"
		return
	fi
	bar=$(magick "$2" -crop "$HUD_BAR" +repage -fill white +opaque "rgb(255,255,0)" \
		-fill black -opaque "rgb(255,255,0)" -format "%[fx:round(mean*w*h)]" info:)
	if [ "$bar" != "0" ]; then
		echo "$bar pixels of the opaque bar are not its colour"
		return
	fi
	magick "$1" -crop "$HUD_PANEL" +repage -evaluate divide 2 "$WORK/hudHalf.ppm"
	magick "$2" -crop "$HUD_PANEL" +repage "$WORK/hudPanel.ppm"
	panel=$(magick "$WORK/hudHalf.ppm" "$WORK/hudPanel.ppm" -compose difference -composite \
		-separate -append -format "%[fx:round(maxima*255)]" info: 2>&1)
	case "$panel" in
		'' | *[!0-9]*)
			echo "the panel difference could not be measured: $panel"
			return
			;;
	esac
	if [ "$panel" -gt 1 ]; then
		echo "the panel is off half of the campfire under it by up to $panel in a channel"
	fi
}

run_hud_over_campfire() {
	if ! command -v magick > /dev/null 2>&1; then
		skip "hud: ImageMagick is not on PATH — the HUD frames were not checked"
		return
	fi
	build_and_capture campfireHudCapture || return
	build_and_capture campfireHudSwappedCapture || return
	caught=0
	for frame in $FRAMES; do
		under=$CAPTURE/gate/campfireCapture_$frame.ppm
		over=$CAPTURE/gate/campfireHudCapture_$frame.ppm
		swapped=$CAPTURE/gate/campfireHudSwappedCapture_$frame.ppm
		if [ ! -f "$under" ] || [ ! -f "$over" ] || [ ! -f "$swapped" ]; then
			fail "hud: frame $frame of campfireCapture or a HUD capture was not captured"
			return
		fi
		wrong=$(hud_mismatch "$under" "$over")
		if [ -n "$wrong" ]; then
			fail "hud: frame $frame, $wrong"
			return
		fi
		case "$(hud_mismatch "$under" "$swapped")" in
			*"of the opaque bar are not its colour"*) caught=$((caught + 1)) ;;
		esac
	done
	if [ "$caught" -ne 4 ]; then
		fail "hud: the control, the campfire drawn over the HUD, passed the checks in $((4 - caught)) of 4 frames"
		return
	fi
	pass "hud: void2d over the pixel-art campfire, the rest byte-identical, bar exact, panel half; the control fails in 4 of 4"
}

