PICK_PATH_FUNCTIONS="pick:pickNearest pick:pickableOwner pick:meshHit bounds:rayIntersection
	mesh68ata:rayIntersection mesh68ata:cornerOf ray:transformed"

# $1 entry, $2 label, $3 the module:function list. Prints nothing and returns 0 when clean;
# otherwise records the failure and returns 1.
check_array_copies() {
	rm -f out/debug/*ZsrcZvoid3dZ*Oms.c
	if ! msc build "$1" --emit=c > "$WORK/allocation.log" 2>&1; then
		fail "allocation: emitting C for $1 failed; see $WORK/allocation.log"
		return 1
	fi
	offenders=""
	for entry in $3; do
		module=${entry%%:*}
		fn=${entry#*:}
		emitted=$(ls out/debug/*ZsrcZvoid3dZ${module}Oms.c 2>/dev/null | head -1)
		if [ -z "$emitted" ] || ! grep -q "^[a-zA-Z_].*[^a-zA-Z0-9_]${fn}__M.*{[[:space:]]*$" "$emitted"; then
			fail "allocation: the emitted C of $module.ms has no body for $fn — renamed or unreachable?"
			return 1
		fi
		copies=$(awk "/^[a-zA-Z_].*\y${fn}__M.*\{[ \t]*\$/,/^}/" "$emitted" |
			grep -c 'ArrayCopy(' || true)
		[ "$copies" -gt 0 ] && offenders="$offenders ${fn}=${copies}"
	done
	if [ -n "$offenders" ]; then
		fail "allocation: the $2 copies an array — ArrayCopy in:$offenders"
		echo "         CODE-STYLE section 5, the copy trap: index the field or take a Span view"
		return 1
	fi
	return 0
}

run_allocation() {
	if [ ! -f "$CAPTURE/campfireBench.ms" ] || [ ! -f "$CAPTURE/campfirePick.ms" ]; then
		skip "allocation: $CAPTURE/campfireBench.ms or campfirePick.ms is missing"
		return
	fi
	check_array_copies "$CAPTURE/campfireBench.ms" "frame path" \
		"$FRAME_PATH_FUNCTIONS $RENDER_PATH_FUNCTIONS" || return
	check_array_copies "$CAPTURE/campfirePick.ms" "pick path" "$PICK_PATH_FUNCTIONS" || return
	pass "allocation: no array copy in the frame path ($(echo $FRAME_PATH_FUNCTIONS))"
	note "allocation: nor in the render path ($(echo $RENDER_PATH_FUNCTIONS))"
	note "allocation: nor in the pick path ($(echo $PICK_PATH_FUNCTIONS))"
}

# ---- pending ------------------------------------------------------------------------------

# tests/PENDING3D.md on rexa's rule: a listed case that stops holding fails the run, and its row
# is deleted in the same commit as the fix. Enforced in both directions, because a list with a
# forcing function in only one direction rots from the other end.
#
# What this stage sees is that a **sentinel is present**, not that the **divergence still
# holds** — measured: fixing `size()` while leaving its `// PENDING3D:` line in place passes
# here and fails `oracle`. Only the rows with a `diverges=` oracle case are enforced
# behaviourally; tests/PENDING3D.md names them. The `*)` branch
# below is deliberately a requirement and not a skip: a row naming a sentinel nobody wrote
# fails rather than passing quietly.
run_pending() {
	if [ ! -f "$PENDING" ]; then
		skip "pending: $PENDING is missing, so nothing holds the known divergences to account"
		return
	fi
	rows=$(grep -oE '^\| `[a-z0-9-]+`' "$PENDING" | tr -d '|` ' | sort)
	tags=$(grep -rhoE 'PENDING3D: [a-z0-9-]+' src/ | sed 's/PENDING3D: //' | sort -u)
	graduated=""
	for row in $rows; do
		case "$row" in
			baselines-adopted-circular)
				grep -q 'plausible\* M4 images' docs/VOID3D.md || graduated="$graduated $row" ;;
			gles3-emulator-only)
				grep -q 'not a device' docs/VOID3D.md || graduated="$graduated $row" ;;
			*)
				echo "$tags" | grep -qx "$row" || graduated="$graduated $row" ;;
		esac
	done
	unlisted=""
	for tag in $tags; do
		echo "$rows" | grep -qx "$tag" || unlisted="$unlisted $tag"
	done
	if [ -n "$graduated" ]; then
		fail "pending: listed but no longer holding — delete the row in the commit that fixed it:$graduated"
		return
	fi
	if [ -n "$unlisted" ]; then
		fail "pending: marked in the tree with no row in $PENDING:$unlisted"
		return
	fi
	count=$(echo "$rows" | grep -c .)
	pass "pending: $count rows in $PENDING, every sentinel present and every sentinel listed"
}

