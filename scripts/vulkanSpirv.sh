#!/bin/bash
# Regenerate tests/integration/vulkanSpirv.ms from the WGSL beside it with naga. The Vulkan
# backend flips the viewport, so the SPIR-V keeps WebGPU's coordinate space.
set -e
cd "$(dirname "$0")/.."
OUT=tests/integration/vulkanSpirv.ms
SCRATCH=$(mktemp -d)
trap 'rm -rf "$SCRATCH"' EXIT
{
	echo "// Generated by scripts/vulkanSpirv.sh from tests/integration/vulkan{Draw,Compute}.wgsl ($(naga --version | tr -d '\r')); do not edit."
	for name in Draw Compute; do
		naga --keep-coordinate-space "tests/integration/vulkan$name.wgsl" "$SCRATCH/$name.spv"
		echo
		echo "export function spirv$name(): Vec<uint8> {"
		printf '\treturn ['
		od -An -v -tu1 "$SCRATCH/$name.spv" | tr -s ' \n' ' ' | sed 's/^ //; s/ $//; s/ /, /g' | fold -s -w 96 | sed '2,$s/^/\t\t/' | sed 's/ $//'
		echo '] as Vec<uint8>;'
		echo "}"
	done
} > "$OUT"
