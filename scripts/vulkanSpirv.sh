#!/bin/bash
# Regenerate src/test/vulkanSpirv.ms from the WGSL beside it with naga. The Vulkan
# backend flips the viewport, so the SPIR-V keeps WebGPU's coordinate space.
set -e
cd "$(dirname "$0")/.."
OUT=src/test/vulkanSpirv.ms
SCRATCH=$(mktemp -d)
trap 'rm -rf "$SCRATCH"' EXIT
{
	echo "// Generated by scripts/vulkanSpirv.sh from src/test/vulkan{Flat,Textured,Tint,Compute,Coloured}.wgsl ($(naga --version | tr -d '\r')); do not edit."
	for name in Flat Textured Tint Compute Coloured; do
		naga --keep-coordinate-space "src/test/vulkan$name.wgsl" "$SCRATCH/$name.spv"
		echo
		echo "export function spirv$name(): Vec<uint8> {"
		printf '\treturn ['
		od -An -v -tu1 "$SCRATCH/$name.spv" | tr -s ' \n' ' ' | sed 's/^ //; s/ $//; s/ /, /g' | fold -s -w 96 | sed '2,$s/^/\t\t/' | sed 's/ $//'
		echo '] as Vec<uint8>;'
		echo "}"
	done
} > "$OUT"
