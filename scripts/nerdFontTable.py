"""Writes src/void2d/nerdFontTable.ms from Ghostty's src/font/nerd_font_tables.zig.

    python3 -I scripts/nerdFontTable.py <ghostty>/src/font/nerd_font_tables.zig > src/void2d/nerdFontTable.ms

The zig file is three stages: stage1 maps a codepoint's high bits to a stage2 block offset, stage2
maps the low byte to a stage3 index, stage3 holds the constraints (index 0 is none). This script
keeps stage3 as the constraint list and turns stages 1-2 into sorted ranges.
"""
import base64
import re
import sys

SHIFT = 9
FIELDS = {
    "size": ("size", "NerdSize", "None"),
    "align_vertical": ("alignVertical", "NerdAlign", "None"),
    "align_horizontal": ("alignHorizontal", "NerdAlign", "None"),
    "height": ("height", "NerdHeight", "Cell"),
}
NUMBERS = {
    "pad_top": ("padTop", 0.0),
    "pad_left": ("padLeft", 0.0),
    "pad_right": ("padRight", 0.0),
    "pad_bottom": ("padBottom", 0.0),
    "relative_width": ("relWidth", 1.0),
    "relative_height": ("relHeight", 1.0),
    "relative_x": ("relX", 0.0),
    "relative_y": ("relY", 0.0),
    "max_xy_ratio": ("maxXyRatio", 0.0),
    "max_constraint_width": ("maxConstraintWidth", 2),
}


def camel(word):
    return "".join(part.capitalize() for part in word.split("_"))


def words(source, name):
    body = re.search(r"pub const " + name + r": \[\d+\]u16 = \.\{(.*?)\};", source, re.S).group(1)
    return [int(x) for x in body.split(",") if x.strip()]


def constraints(source):
    body = source.split("pub const stage3", 1)[1].split("= .{", 1)[1]
    out = []
    for item in re.finditer(r"^            (null|\.\{.*?^            \}),$", body, re.S | re.M):
        text = item.group(1)
        out.append(None if text == "null" else dict(re.findall(r"\.(\w+) = ([^,\n]+),", text)))
    return out


def literal(entry):
    parts = []
    for key, (name, enum, default) in FIELDS.items():
        value = camel(entry[key].lstrip(".")) if key in entry else default
        parts.append(f"{name}: {enum}.{value}")
    for key, (name, default) in NUMBERS.items():
        value = entry.get(key, default)
        if key == "max_xy_ratio" and value in ("null", 0.0):
            value = 0.0
        parts.append(f"{name}: {value if key == 'max_constraint_width' else float(value)}")
    return "{ " + ", ".join(parts) + " }"


def varints(ranges):
    out = bytearray()
    previous = 0
    for start, value in ranges:
        word = ((start - previous) << SHIFT) | value
        previous = start
        while word >= 0x80:
            out.append((word & 0x7F) | 0x80)
            word >>= 7
        out.append(word)
    return base64.b64encode(bytes(out)).decode()


def main(path):
    source = open(path).read()
    stage1, stage2, stage3 = words(source, "stage1"), words(source, "stage2"), constraints(source)
    mapped = {}
    for high, block in enumerate(stage1):
        if block == 0:
            continue
        for low in range(256):
            if stage2[block + low]:
                mapped[high * 256 + low] = stage2[block + low]
    ranges, last, previous = [], 0, None
    for cp in sorted(mapped):
        if previous is not None and cp != previous + 1 and last != 0:
            ranges.append((previous + 1, 0))
            last = 0
        if mapped[cp] != last:
            ranges.append((cp, mapped[cp]))
            last = mapped[cp]
        previous = cp
    ranges.append((previous + 1, 0))
    ranges.insert(0, (0, 0))
    assert len(stage3) < (1 << SHIFT)
    print("// Generated by scripts/nerdFontTable.py from Ghostty's src/font/nerd_font_tables.zig. Do not edit.")
    print(f"// Ranges are (start << {SHIFT}) | index into NERD_CONSTRAINTS, sorted, stored as base64 of one")
    print("// LEB128 varint per range with the start as a delta (unpackRanges, unicodeRanges.ms); index 0")
    print("// is no constraint.")
    print()
    print("export enum NerdSize { None, Fit, Cover, FitCover1, Stretch }")
    print()
    print("export enum NerdAlign { None, Start, End, Center, Center1 }")
    print()
    print("export enum NerdHeight { Cell, Icon }")
    print()
    print("export struct NerdConstraint {")
    for key, (name, enum, _) in FIELDS.items():
        print(f"\t{name}: {enum};")
    for key, (name, default) in NUMBERS.items():
        print(f"\t{name}: {'int32' if key == 'max_constraint_width' else 'float32'};")
    print("}")
    print()
    print(f"export const NERD_SHIFT: uint32 = {SHIFT};")
    print()
    print(f'export const NERD_RANGES_PACKED: string = "{varints(ranges)}";')
    print()
    print("export const NERD_CONSTRAINTS: NerdConstraint[] = [")
    for entry in stage3:
        print("\t" + literal(entry if entry else {}) + ",")
    print("];")


main(sys.argv[1])
