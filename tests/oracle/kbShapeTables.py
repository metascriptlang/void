def msname(cname):
    return "KB_" + re.sub(r"^KBTS_+", "", cname)


def strip_comments(text):
    return re.sub(r"//[^\n]*|/\*.*?\*/", "", text, flags=re.S)


def top_level_split(text):
    parts, depth, at = [], 0, 0
    for i, c in enumerate(text):
        if c in "({":
            depth += 1
        elif c in ")}":
            depth -= 1
        elif c == "," and depth == 0:
            parts.append(text[at:i])
            at = i + 1
    parts.append(text[at:])
    return [p.strip() for p in parts if p.strip()]


def balanced(text, start):
    depth = 0
    for i in range(start, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[start + 1:i]
    raise SystemExit("unbalanced braces")


def fourcc(m):
    chars = [c.strip() for c in m.group(1).split(",")]
    if len(chars) != 4:
        raise SystemExit(f"FOURCC with {len(chars)} arguments: {m.group(0)}")
    value = 0
    for i, c in enumerate(chars):
        value |= (ord(c[1]) if c.startswith("'") else int(c, 0)) << (8 * i)
    return str(value)


class Evaluator:
    def __init__(self):
        self.env = {}

    def value(self, expr):
        text = strip_comments(expr)
        text = re.sub(r"KBTS_FOURCC\(([^)]*)\)", fourcc, text)
        text = re.sub(r"KBTS__FEATURE_FLAG(\d)\((\w+)\)", self.feature_flag, text)
        text = re.sub(r"\(kbts_(?:u\d+|un)\)", "", text)
        text = re.sub(r"\b(0x[0-9a-fA-F]+|\d+)(?:ull|u)\b", r"\1", text)
        text = re.sub(r"\bKBTS_\w+", self.lookup, text)
        if not re.fullmatch(r"[0-9a-fA-Fx\s()|&<>+\-~*]*", text):
            raise SystemExit(f"cannot evaluate {expr!r}: {text!r}")
        return eval(text, {"__builtins__": {}})

    def lookup(self, m):
        if m.group(0) not in self.env:
            raise SystemExit(f"unknown name {m.group(0)}")
        return str(self.env[m.group(0)])

    def feature_flag(self, m):
        name = "KBTS__FEATURE_ID_" + m.group(2)
        if name not in self.env:
            raise SystemExit(f"unknown feature {m.group(2)}")
        return f"(1 << ({self.env[name]} - {64 * int(m.group(1))}))"


def enum_body(text, name, first_member):
    if name:
        m = re.search(r"enum " + name + r"\s*\{", text)
    else:
        m = re.search(r"enum\s*\{[^}]*?\b" + first_member + r"\b", text)
    if not m:
        raise SystemExit(f"enum {name!r} {first_member!r} not found")
    return balanced(text, text.index("{", m.start()))


def enum_type(text, name):
    typedef = ENUM_TYPEDEFS.get(name) or (name and name[:-len("_enum")])
    m = typedef and re.search(r"typedef (kbts_u\d+) " + typedef + ";", text)
    return TYPES[m.group(1)] if m else "uint32"


def enum_entries(text, ev, name, first_member=None):
    out, nxt = [], 0
    for entry in top_level_split(strip_comments(enum_body(text, name, first_member))):
        if "=" in entry:
            cname, expr = [s.strip() for s in entry.split("=", 1)]
            nxt = ev.value(expr)
        else:
            cname = entry
        ev.env[cname] = nxt
        out.append((cname, nxt))
        nxt += 1
    return out


def wrap(name, kind, values):
    lines, row = [f"export const {name}: {kind}[] = ["], "\t"
    for v in values:
        piece = f"{v},"
        if len(row) + len(piece) > WIDTH and row != "\t":
            lines.append(row)
            row = "\t"
        row += piece
    if row != "\t":
        lines.append(row)
    lines.append("];")
    return lines


def defines(text):
    joined = re.sub(r"\\\n", " ", text)
    found = {}
    for m in re.finditer(r"^#\s*define\s+(\w+)(\(([^)]*)\))?[ \t]+(.*)$", joined, re.M):
        found.setdefault(m.group(1), (m.group(3), m.group(4).strip()))
    return found


def feature_ids(ev):
    return {n[len("KBTS__FEATURE_ID_"):]: v for n, v in ev.env.items()
            if n.startswith("KBTS__FEATURE_ID_")}


def feature_words(expr_words, ids, where):
    if len(expr_words) != 4:
        raise SystemExit(f"{where}: feature set with {len(expr_words)} words")
    words = []
    for position, word in enumerate(expr_words):
        value = 0
        for token in [t.strip() for t in word.split("|")]:
            if token in ("0", "0ull"):
                continue
            m = re.fullmatch(r"KBTS__FEATURE_FLAG(\d)\((\w+)\)", token)
            if not m or int(m.group(1)) != position:
                raise SystemExit(f"{where}: word {position} has {token!r}")
            bit = ids[m.group(2)] - 64 * position
            if not 0 <= bit < 64:
                raise SystemExit(f"{where}: {m.group(2)} is not in word {position}")
            value |= 1 << bit
        words.append(value)
    return words


def op_list(text, name, ids, ev):
    ops = re.search(r"static kbts__op_kind kbts__Ops_" + name + r"\[\] = \{(.*?)\};", text, re.S)
    stages = re.search(r"static kbts__feature_stage kbts__FeatureStages_" + name
                       + r"\[\] = \{(.*?)\n\};", text, re.S)
    head = re.search(r"static kbts__op_list kbts__OpList_" + name + r" = \{(\d+), ", text)
    if not (ops and stages and head):
        raise SystemExit(f"op list {name} not found")
    kinds = [k.strip() for k in strip_comments(ops.group(1)).split(",") if k.strip()]
    counts, flags = [], []
    for line in stages.group(1).strip().split("\n"):
        m = re.fullmatch(r"\s*\{(\d+), \{\{(.*)\}\}\},", line)
        if not m:
            raise SystemExit(f"{name}: stage line {line[:60]!r}")
        counts.append(int(m.group(1)))
        flags += feature_words(m.group(2).split(","), ids, f"{name} stage {len(counts) - 1}")
    total = int(head.group(1))
    if sum(counts) != total:
        raise SystemExit(f"{name}: stage feature counts sum to {sum(counts)}, header says {total}")
    return total, counts, flags, [msname(k) for k in kinds]


def op_list_block(const, parsed):
    total, counts, flags, kinds = parsed
    out = [f"export const KB_OP_LIST_{const}: KbOpList = {{",
           f"\ttotalFeatureCount: {total},"]
    for field, kind, values in (("stageFeatureCounts", "uint32", counts),
                                ("stageFlags", "uint64", flags), ("ops", "uint8", kinds)):
        body = wrap("x", kind, [str(v) for v in values])
        out.append(f"\t{field}: [")
        out += ["\t" + line for line in body[1:-1]]
        out.append("\t],")
    return out + ["};"]


def op_lists(text, ev):
    ids = feature_ids(ev)
    parsed = {n: op_list(text, n, ids, ev) for n in OP_LISTS}
    m = re.search(r"static kbts__op_list \*kbts__ShaperOpLists\[KBTS_SHAPER_COUNT\] = \{(.*?)\};",
                  text, re.S)
    rows = re.findall(r"/\*\s*(\w+),\s*\*/\s*&kbts__OpList_(\w+),", m.group(1))
    shapers = [n for n, _ in sorted(((n[len("KBTS_SHAPER_"):], v) for n, v in ev.env.items()
                                     if re.fullmatch(r"KBTS_SHAPER_[A-Z]+", n)
                                     and n != "KBTS_SHAPER_COUNT"), key=lambda p: p[1])]
    if [r[0] for r in rows] != shapers or len(rows) != ev.env["KBTS_SHAPER_COUNT"]:
        raise SystemExit(f"ShaperOpLists rows {[r[0] for r in rows]} against shapers {shapers}")
    out = ["export struct KbOpList {", "\ttotalFeatureCount: uint32;", "\tstageFeatureCounts: uint32[];",
           "\tstageFlags: uint64[];", "\tops: uint8[];", "}", ""]
    for n in OP_LISTS:
        out += op_list_block(screaming(n), parsed[n]) + [""]
    out.append("export const KB_SHAPER_OP_LISTS: KbOpList[] = [")
    out += [f"\tKB_OP_LIST_{screaming(r[1])}," for r in rows]
    out.append("];")
    syllable = re.search(r"kbts__feature_set SyllableFeatureSet = \{\{(.*?)\}\};", text, re.S)
    words = feature_words([w.strip() for w in top_level_split(syllable.group(1))], ids,
                          "SyllableFeatureSet")
    return out + [""] + wrap("KB_SYLLABLE_FEATURE_SET", "uint64", [str(w) for w in words]), parsed


def screaming(name):
    return re.sub(r"(?<=[a-z])(?=[A-Z])", "_", name).upper()


def script_tables(text, ev):
    count = ev.env["KBTS_SCRIPT_COUNT"]
    m = re.search(r"static kbts__script_properties kbts__ScriptProperties\[KBTS_SCRIPT_COUNT\] = \{"
                  r"(.*?)\n\};", text, re.S)
    rows = re.findall(r"\{(KBTS_FOURCC\([^)]*\)), (KBTS_SHAPER_\w+)\},", m.group(1))
    if len(rows) != count or m.group(1).count("{") != count:
        raise SystemExit(f"ScriptProperties has {len(rows)} rows, KBTS_SCRIPT_COUNT is {count}")
    tags = [ev.value(r[0]) for r in rows]
    shapers = [ev.value(r[1]) for r in rows]
    out = wrap("KB_SCRIPT_TAGS", "uint32", [str(t) for t in tags])
    out += wrap("KB_SCRIPT_SHAPERS", "uint8", [str(s) for s in shapers])
    return out


def indic_script_properties(text, ev):
    start = text.index("static kbts__indic_script_properties kbts__IndicScriptProperties(")
    body = text[start:text.index("\n}\n", start)]
    per_script = {}
    cases = re.findall(r"case (KBTS_SCRIPT_\w+):\s*\{(.*?)\}\s*break;", body, re.S)
    if len(cases) != body.count("case "):
        raise SystemExit("IndicScriptProperties has a case the generator does not read")
    known = {c for c, _, _ in INDIC_FIELDS}
    for script, assigns in cases:
        fields = {}
        for field, expr in re.findall(r"Result\.(\w+) = ([^;]+);", assigns):
            if field not in known:
                raise SystemExit(f"IndicScriptProperties sets unknown field {field}")
            fields[field] = ev.value(expr)
        if script in per_script:
            raise SystemExit(f"IndicScriptProperties repeats {script}")
        per_script[ev.env[script]] = fields
    out = []
    for field, name, kind in INDIC_FIELDS:
        column = [per_script.get(i, {}).get(field, 0) for i in range(ev.env["KBTS_SCRIPT_COUNT"])]
        out += wrap(f"KB_INDIC_SCRIPT_{name}", kind, [str(v) for v in column])
    return out


def script_tag_to_script(text, ev):
    start = text.index("KBTS_EXPORT kbts_script kbts_ScriptTagToScript(kbts_script_tag Tag)\n{")
    body = text[text.index("switch(Tag)", start):text.index("\n}\n", start)]
    cases = re.findall(r"case (KBTS_SCRIPT_TAG_\w+): Result = (KBTS_SCRIPT_\w+); break;", body)
    if len(cases) != body.count("case "):
        raise SystemExit("ScriptTagToScript has a case the generator does not read")
    seen = set()
    out = ["export function kbScriptTagToScript(tag: uint32): uint32 {", "\tmatch (tag) {"]
    for tag, script in cases:
        if ev.env[tag] in seen:
            raise SystemExit(f"ScriptTagToScript repeats {tag}")
        seen.add(ev.env[tag])
        out.append(f"\t\t{ev.env[tag]} => {{ return {msname(script)}; }},")
    out += [f"\t\t_ => {{ return {msname('KBTS_SCRIPT_DONT_KNOW')}; }},", "\t}", "}"]
    return out


def transitions(text, ev):
    out = []
    for name, cname, classes, states in TRANSITIONS:
        m = re.search(r"static kbts_u8 " + cname + r"\[[^=]*= \{(.*?)^\};", text, re.S | re.M)
        rows = re.findall(r"/\*\s*\w+\s*\*/\s*\{([^}]*)\}", m.group(1))
        cells = [[int(v) for v in row.split(",") if v.strip()] for row in rows]
        want_rows, want_cols = ev.value(classes), ev.value(states)
        if len(cells) != want_rows or any(len(r) != want_cols for r in cells):
            raise SystemExit(f"{cname}: {len(cells)} rows of {sorted({len(r) for r in cells})}, "
                             f"want {want_rows} x {want_cols}")
        out += wrap(f"KB_{name}_TRANSITION", "uint8", [str(v) for r in cells for v in r])
    return out


def invalid_indic_clusters(text):
    start = text.index("#define KBTS_C2(A, B)")
    end = text.index("#undef KBTS_C2", start)
    block = text[start:end]
    pairs = [(int(a, 0), int(b, 0)) for a, b in re.findall(r"KBTS_C2\((0x\w+), (0x\w+)\)", block[40:])]
    if len(pairs) != block.count("KBTS_C2(") - 1 or len(set(pairs)) != len(pairs):
        raise SystemExit("invalid Indic clusters: unread or repeated KBTS_C2 entry")
    if re.search(r"switch\(Codepoints & \(\(\(kbts_u64\)1 << 42\) - 1\)\)", block) is None:
        raise SystemExit("invalid Indic clusters: the 42-bit window moved")
    triple = re.search(r"\(\(Codepoints & \(\(\(kbts_u64\)1 << 63\) - 1\)\) == \(\(\(kbts_u64\)(0x\w+) << 42\) "
                       r"\| \(\(kbts_u64\)(0x\w+) << 21\) \| \(\(kbts_u64\)(0x\w+)\)\)\)", block)
    if not triple:
        raise SystemExit("invalid Indic clusters: the default three-codepoint check moved")
    a, b, c = (int(g, 0) for g in triple.groups())
    keys = sorted(x << 21 | y for x, y in pairs)
    out = wrap("KB_INVALID_INDIC_PAIRS", "uint64", [str(k) for k in keys]) + [
        f"export const KB_INVALID_INDIC_PAIR_MASK: uint64 = {(1 << 42) - 1};",
        f"export const KB_INVALID_INDIC_TRIPLE_MASK: uint64 = {(1 << 63) - 1};",
        f"export const KB_INVALID_INDIC_TRIPLE: uint64 = {a << 42 | b << 21 | c};", "",
        "export function kbInvalidIndicCluster(codepoints: uint64): boolean {",
        "	if ((codepoints & KB_INVALID_INDIC_TRIPLE_MASK) == KB_INVALID_INDIC_TRIPLE) {",
        "		return true;", "	}",
        "	const key = codepoints & KB_INVALID_INDIC_PAIR_MASK;",
        "	let low: int32 = 0;",
        "	let high: int32 = KB_INVALID_INDIC_PAIRS.length - 1;",
        "	while (low <= high) {",
        "		const middle = (low + high) / 2;",
        "		const found = KB_INVALID_INDIC_PAIRS[middle];",
        "		if (found == key) { return true; }",
        "		if (found < key) { low = middle + 1; } else { high = middle - 1; }",
        "	}",
        "	return false;", "}"]
    return out, len(keys)


def match_masks(text, ev, defs):
    params, body = defs["KBTS__FEATURE_MATCH_MASK"]
    names = [p.strip() for p in params.split(",")]
    out = []
    for name, (args, expr) in defs.items():
        if not name.startswith("KBTS__FEATURE_MATCH_MASK_"):
            continue
        m = re.fullmatch(r"KBTS__FEATURE_MATCH_MASK\((.*)\)", expr)
        values = [ev.value(a) for a in top_level_split(m.group(1))]
        if len(values) != len(names):
            raise SystemExit(f"{name}: {len(values)} arguments")
        text_body = body
        for p, v in zip(names, values):
            text_body = re.sub(r"\b" + p + r"\b", str(v), text_body)
        out.append((name, ev.value(text_body) & MASK64))
    return out


def languages(text):
    ev = Evaluator()
    entries = enum_entries(text, ev, "kbts_language_enum", None)
    seen = {}
    out = [HEADER_LINE]
    for cname, value in entries:
        if cname in seen:
            raise SystemExit(f"duplicate language {cname}")
        seen[cname] = value
        out.append(f"export const {msname(cname)}: uint32 = {value};")
    return out, len(entries)


def main():
    text = open(HEADER, encoding="utf-8").read()
    ev = Evaluator()
    out = [HEADER_LINE,
           "// An enum constant has the width of the C typedef over its enum, else uint32.",
           "// A transition table is flat, read as TABLE[class * STATE_COUNT + state]."]
    names, counts = set(), {}
    enum_entries(text, ev, "kbts__feature_id_enum")
    for group, silent in ((SILENT_ENUMS, True), (ENUMS, False)):
        for name, first in group:
            entries = enum_entries(text, ev, name, first)
            counts[name or first] = len(entries)
            kind = enum_type(text, name)
            if silent:
                continue
            for cname, value in entries:
                if msname(cname) in names:
                    raise SystemExit(f"duplicate constant {msname(cname)}")
                names.add(msname(cname))
                if not 0 <= value < 1 << WIDTHS[kind]:
                    raise SystemExit(f"{cname} = {value} does not fit {kind}")
                out.append(f"export const {msname(cname)}: {kind} = {value};")
    defs = defines(text)
    for cname in DEFINES:
        params, expr = defs[cname]
        value = ev.value(expr)
        ev.env[cname] = value
        out.append(f"export const {msname(cname)}: uint32 = {value};")
    for cname in UINT64_DEFINES:
        params, expr = defs[cname]
        out.append(f"export const {msname(cname)}: uint64 = {ev.value(expr)};")
    if (ev.env["KBTS_SCRIPT_COUNT"] != counts["kbts_script_enum"] - 1
            or ev.env["KBTS_SHAPER_COUNT"] != counts["kbts_shaper_enum"] - 1):
        raise SystemExit("an enum COUNT is not its last entry")
    out += [""] + script_tables(text, ev) + [""] + indic_script_properties(text, ev) + [""]
    lists, parsed = op_lists(text, ev)
    out += lists + [""] + transitions(text, ev) + [""]
    cluster, pair_count = invalid_indic_clusters(text)
    out += cluster + [""] + script_tag_to_script(text, ev) + [""]
    masks = match_masks(text, ev, defs)
    out += [f"export const {msname(n)}: uint64 = {v};" for n, v in masks]
    open(OUTPUT, "w", newline="\n").write("\n".join(out) + "\n")
    language_lines, language_count = languages(text)
    open(LANGUAGES_OUTPUT, "w", newline="\n").write("\n".join(language_lines) + "\n")
