"""The kb_text_shape shaping data: python tests/oracle/kbShapeTables.py

Reads deps/kb/kb_text_shape.h and writes
  src/void2d/kb/shapeTables.ms  the enums and numeric defines the shaping core names, the script
                                tags and shapers, the Indic script properties, the op lists with
                                their feature stages as uint64 x4 bitsets, the Indic, Myanmar,
                                Khmer and USE syllable transitions, the invalid Indic clusters,
                                the Indic feature-match masks and kbts_ScriptTagToScript
  src/void2d/kb/languages.ms    kbts_language_enum, apart so only a caller that names a language
                                carries it
Element types are the C's; a transition table is flat, read as TABLE[class * STATE_COUNT + state].
The gate needs none of it: the outputs are committed and src/test/kbShapeTablesCheck.ms pins
them against digests recorded from the C.
"""
